<h2>1.- ¿Qué es una cookie y para qué sirve?</h2>
<p>Una cookie es un archivo que se descarga en su ordenador, smartphone, tableta, etc., al acceder a determinadas páginas web. Las cookies permiten a una página web, entre otras cosas, almacenar y recuperar información sobre los hábitos de navegación de un usuario o de su equipo y, dependiendo de la información que contengan y de la forma en que utilice su equipo, pueden utilizarse para reconocer al usuario.</p>
<h2>2.- ¿Clasificación de las cookies?</h2>
<p>Las cookies pueden clasificarse de la siguiente manera:</p>
<p>A. Según la entidad que las gestione:</p>
<p>a) Cookies propias: Son aquellas que se envían a su equipo desde nuestros propios servidores o dominios y desde los que prestamos el servicio que usted solicita.</p>
<p>b) Cookies de terceros: Son aquellas que se envían a su equipo desde un equipo o dominio que no es gestionado por nosotros, sino por otra entidad colaboradora. Por ejemplo, las utilizadas por redes sociales.</p>
<p>B. Según el plazo de tiempo que permanecen activadas:</p>
<p>a) Cookies de sesión: Son cookies temporales que permanecen en el archivo de cookies de su navegador hasta que abandona el sitio web, de modo que ninguna queda registrada en el disco duro de su ordenador.</p>
<p>b) Cookies persistentes: Se almacenan en el disco duro y nuestra web las lee cada vez que usted vuelve a visitarla. Una cookie permanente tiene una fecha de caducidad; la cookie dejará de funcionar después de esa fecha.</p>
<p>C. Según su finalidad:</p>
<p>a) Cookies técnicas: Son necesarias para la navegación y para la ejecución de determinadas funciones de nuestro sitio web.<br />
b) Cookies de personalización: Permiten acceder al servicio con características predefinidas según una serie de criterios, como el idioma, el tipo de navegador utilizado para acceder al servicio, la configuración regional desde la que se accede, etc.<br />
c) Cookies de análisis: Permiten cuantificar el número de usuarios y así realizar la medición y análisis estadístico del uso que hacen los usuarios de los servicios ofrecidos.<br />
d) Cookies publicitarias: Permiten la gestión, de la forma más eficaz posible, de los espacios publicitarios que puedan incluirse en una página web.</p>
